def explain(gid):
    """(text, sure) for a game setting: sure is False for the Workshop's own best guesses."""
    k = gid.lower()
    if k in SURE:
        return SURE[k], True
    if k in MORE:
        return MORE[k], False
    if k.startswith('s'):
        return 'Words the game shows (a menu, a message or a name). Change it to reword what players see.', False
    return 'Not used by the base game; a mod added it, so it does whatever that mod decided.', False
